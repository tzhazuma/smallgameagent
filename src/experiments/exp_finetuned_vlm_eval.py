#!/usr/bin/env python3
"""Evaluate the fine-tuned VLM's visual context quality vs the base model.

Compares the visual summary generated by the fine-tuned adapter (served by
src/inference/server.py /predict endpoint) against the base model, and then
checks how well the cloud API (qwen) can use the summary to pick the right move.

This is the post-QLoRA evaluation for the L1 scene-understanding layer.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT))

from src.experiments.game_env import score_trajectory  # noqa: E402
from src.experiments import offline_replay as replay  # noqa: E402


def predict_local(endpoint: str, image_path: str, state: dict) -> dict:
    """Call the fine-tuned VLM server /predict endpoint."""
    import base64
    b64 = base64.b64encode(Path(image_path).read_bytes()).decode("ascii")
    payload = json.dumps({"image_base64": b64, "state_json": json.dumps(state)}).encode()
    req = urllib.request.Request(
        f"{endpoint.rstrip('/')}/predict",
        data=payload,
        headers={"Content-Type": "application/json"},
    )
    t0 = time.time()
    resp = urllib.request.urlopen(req, timeout=120)
    out = json.loads(resp.read())
    return {"latency": time.time() - t0, "result": out}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--endpoint", default="http://127.0.0.1:8000", help="Fine-tuned VLM server")
    ap.add_argument("--game", default="SSD_00461P01")
    ap.add_argument("--steps", type=int, default=5)
    args = ap.parse_args()

    steps = replay.load_steps(ROOT / "processed-runs" / args.game)[: args.steps]
    print(f"[eval] {args.game}, {len(steps)} steps, endpoint={args.endpoint}")
    for i, st in enumerate(steps):
        img = st.get("screenshot_path") or (ROOT / "processed-runs" / args.game / "screenshots" / f"{i:05d}.png")
        if not Path(img).exists():
            print(f"  step {i}: no screenshot, skip")
            continue
        try:
            r = predict_local(args.endpoint, str(img), st.get("state", {}))
            res = r["result"]
            print(f"  step {i}: {r['latency']:.1f}s -> {json.dumps(res, ensure_ascii=False)[:200]}")
        except Exception as e:
            print(f"  step {i}: ERR {e}")


if __name__ == "__main__":
    main()
