#!/usr/bin/env python3
"""Local VLM visual understanding + cloud API strategy comparison.

Loads a few steps from ``processed-runs/SSD_00461P01`` and compares cloud API
action predictions in two conditions:

1. Cloud sees only the probe state (text-only baseline).
2. Cloud sees probe state + a concise visual summary generated by the local
   VLM (Qwen3.5-4B / Gemma-4-E4B via llama.cpp / LM Studio).

The visual summary is produced with a permissive prompt: the small local model
is allowed to output free-form text, and we feed that text to the cloud model
as additional context.  This mirrors the intended three-layer design where the
local VLM is a "slow but cheap understanding layer" and the cloud API is the
"strategic decision layer".

Usage::

    # 1. Start llama-server with a vision GGUF, e.g. Qwen3.5-4B-Q4_K_M.gguf
    # 2. Run:
    . .env && PYTHONPATH=. .venv/bin/python -B \
        src/experiments/exp_local_vlm_cloud_context.py --provider qwen --num-steps 5
"""

from __future__ import annotations

import argparse
import base64
import json
import logging
import sys
import time
from pathlib import Path
from typing import Any

_PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
if str(_PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(_PROJECT_ROOT))

from src.agent.api_client import MultiProviderClient  # noqa: E402
from src.agent.lmstudio_client import LMStudioClient  # noqa: E402
from src.experiments.offline_replay import (  # noqa: E402
    actions_match,
    adapt_ground_truth,
    adapt_processed_state,
    load_state,
    load_steps,
)

logger = logging.getLogger(__name__)
ROOT = Path(__file__).resolve().parent.parent.parent
PROCESSED_ROOT = ROOT / "processed-runs"


def _load_screenshot(game_dir: Path, step_record: dict[str, Any], key: str = "before") -> bytes | None:
    rel = step_record.get(key, {}).get("screenshot")
    if not rel:
        return None
    path = game_dir / rel
    if not path.is_file():
        return None
    return path.read_bytes()


def _local_vlm_summary(client: LMStudioClient, image_bytes: bytes, state: dict[str, Any]) -> str:
    """Ask the local VLM for a concise visual summary of the screenshot."""
    b64 = base64.b64encode(image_bytes).decode("ascii")
    state_snippet = json.dumps(
        {k: state.get(k) for k in ("player", "keyNumbers") if k in state},
        ensure_ascii=False,
        default=str,
    )[:500]
    messages = [
        {
            "role": "system",
            "content": (
                "You are a game visual analyst. Describe the screenshot concisely for a strategy planner. "
                "Mention: scene type, player location, visible enemies/objects, any arrows/guides, and UI elements. "
                "Output plain text, no markdown."
            ),
        },
        {
            "role": "user",
            "content": [
                {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{b64}"}},
                {"type": "text", "text": f"Game state snippet:\n{state_snippet}\n\nDescribe what you see."},
            ],
        },
    ]
    try:
        resp = client.chat_with_vision(messages, max_tokens=512)
        return client.extract_content(resp) or ""
    except Exception as exc:
        logger.warning("Local VLM call failed: %s", exc)
        return ""


def _cloud_action(provider: str, state: dict[str, Any], visual_summary: str | None = None) -> dict[str, Any]:
    """Ask the cloud API for the next action, optionally with visual context."""
    client = MultiProviderClient(provider=provider)
    state_snippet = json.dumps(
        {k: state.get(k) for k in ("player", "keyNumbers", "guide_or_target_candidates") if k in state},
        ensure_ascii=False,
        default=str,
    )[:1500]
    if visual_summary:
        user_text = (
            "Visual summary from local VLM:\n"
            f"{visual_summary}\n\n"
            f"Game state:\n{state_snippet}\n\n"
            "Output a single JSON action. Normalized move: dx, dy in [-1, 1]. "
            "Tap: x, y in screen pixels. Wait: only duration_ms. "
            "No markdown fences."
        )
    else:
        user_text = (
            f"Game state:\n{state_snippet}\n\n"
            "Output a single JSON action. Normalized move: dx, dy in [-1, 1]. "
            "Tap: x, y in screen pixels. Wait: only duration_ms. "
            "No markdown fences."
        )
    messages = [
        {
            "role": "system",
            "content": (
                "You are an AI agent playing a mobile game. Given the game state and optional visual summary, "
                "output a single JSON object with keys: action, params, reason."
            ),
        },
        {"role": "user", "content": user_text},
    ]
    t0 = time.time()
    resp = client.chat(messages, max_tokens=256, temperature=0.0)
    latency = time.time() - t0
    text = resp.choices[0].message.content or ""
    cleaned = text.strip().strip("`").replace("```json", "").replace("```", "")
    match = __import__("re").search(r"\{[\s\S]*\}", cleaned)
    action = {"action": "wait", "params": {"duration_ms": 500}, "reason": "cloud-fallback"}
    if match:
        try:
            data = json.loads(match.group(0))
            if data.get("action") in ("move", "tap", "wait"):
                action = {
                    "action": data["action"],
                    "params": data.get("params", {}),
                    "reason": data.get("reason", "cloud"),
                }
        except json.JSONDecodeError:
            pass
    action["_raw"] = text[:500]
    action["_latency_s"] = round(latency, 2)
    return action


def run_experiment(
    provider: str = "qwen",
    game_id: str = "SSD_00461P01",
    num_steps: int = 5,
    step_offset: int = 0,
) -> list[dict[str, Any]]:
    """Run the local-VLM + cloud comparison on ``num_steps`` consecutive steps."""
    game_dir = PROCESSED_ROOT / game_id
    if not game_dir.exists():
        raise FileNotFoundError(f"processed run not found: {game_dir}")

    steps = load_steps(game_dir)[step_offset:step_offset + num_steps]
    local_client = LMStudioClient()
    records: list[dict[str, Any]] = []

    for idx, step_record in enumerate(steps):
        step_num = int(step_record.get("step", 0))
        before_raw = load_state(game_dir, step_record.get("before", {}).get("state"))
        if before_raw is None:
            continue
        state = adapt_processed_state(before_raw)
        action_record = load_state(game_dir, step_record.get("action"))
        true_action = adapt_ground_truth(action_record or {"type": "wait"})
        if true_action is None:
            true_action = {"action": "wait", "params": {"duration_ms": 500}, "reason": "unparseable-gt"}

        image_bytes = _load_screenshot(game_dir, step_record, "before")
        visual_summary = ""
        local_latency = 0.0
        if image_bytes is not None:
            t0 = time.time()
            visual_summary = _local_vlm_summary(local_client, image_bytes, state)
            local_latency = time.time() - t0
            logger.info("step %d local VLM latency: %.2fs, summary length: %d", step_num, local_latency, len(visual_summary))

        pred_text_only = _cloud_action(provider, state)
        pred_with_visual = _cloud_action(provider, state, visual_summary)

        _, match_text, _ = actions_match(pred_text_only, true_action)
        _, match_visual, _ = actions_match(pred_with_visual, true_action)

        records.append({
            "step": step_num,
            "provider": provider,
            "local_vlm_latency_s": round(local_latency, 2),
            "visual_summary": visual_summary,
            "true_action": true_action,
            "pred_text_only": pred_text_only,
            "pred_with_visual": pred_with_visual,
            "match_text_only": match_text,
            "match_with_visual": match_visual,
        })

    return records


def main() -> int:
    parser = argparse.ArgumentParser(description="Local VLM + cloud API strategy comparison.")
    parser.add_argument("--provider", default="qwen", choices=["qwen", "kimi", "xiaomi"],
                        help="Cloud provider for strategic decision.")
    parser.add_argument("--game", default="SSD_00461P01", help="Processed-run game ID.")
    parser.add_argument("--num-steps", type=int, default=5, help="Number of steps to evaluate.")
    parser.add_argument("--step-offset", type=int, default=0, help="Start at this step index.")
    parser.add_argument("--verbose", action="store_true", help="Debug logging.")
    args = parser.parse_args()

    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )

    results = run_experiment(
        provider=args.provider,
        game_id=args.game,
        num_steps=args.num_steps,
        step_offset=args.step_offset,
    )

    output_path = ROOT / f"experiment_local_vlm_cloud_context_{args.provider}_{args.game}.json"
    output_path.write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")
    logger.info("Saved %d records to %s", len(results), output_path)

    total = len(results)
    if total > 0:
        text_wins = sum(1 for r in results if r["match_text_only"])
        visual_wins = sum(1 for r in results if r["match_with_visual"])
        logger.info(
            "Summary: text-only match %d/%d, with-visual match %d/%d",
            text_wins, total, visual_wins, total,
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
